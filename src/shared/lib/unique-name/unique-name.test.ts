import { freeName, sameName } from './unique-name';

describe('sameName', () => {
  it('без учёта регистра и пробелов по краям', () => {
    expect(sameName(' Наличные', 'наличные ')).toBe(true);
    expect(sameName('Наличные', 'Наличные (2)')).toBe(false);
  });
});

describe('freeName', () => {
  it('свободное название остаётся как есть', () => {
    expect(freeName('Наличные', ['Основная'])).toBe('Наличные');
    expect(freeName('Наличные', [])).toBe('Наличные');
  });

  it('занятое получает первый свободный номер', () => {
    expect(freeName('Наличные', ['Наличные'])).toBe('Наличные (2)');
    expect(freeName('Наличные', ['Наличные', 'Наличные (2)'])).toBe('Наличные (3)');
    expect(freeName('Наличные', ['Наличные', 'Наличные (3)'])).toBe('Наличные (2)');
  });

  it('регистр и пробелы не мешают заметить занятость', () => {
    expect(freeName('Наличные', [' НАЛИЧНЫЕ '])).toBe('Наличные (2)');
    expect(freeName('Наличные', ['наличные', 'НАЛИЧНЫЕ (2)'])).toBe('Наличные (3)');
  });
});
