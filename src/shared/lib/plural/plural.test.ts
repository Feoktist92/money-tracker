import { pluralRu } from './plural';

const RUB = ['рубль', 'рубля', 'рублей'] as const;

describe('pluralRu', () => {
  it.each([
    [0, 'рублей'],
    [1, 'рубль'],
    [2, 'рубля'],
    [4, 'рубля'],
    [5, 'рублей'],
    [11, 'рублей'],
    [12, 'рублей'],
    [14, 'рублей'],
    [21, 'рубль'],
    [22, 'рубля'],
    [25, 'рублей'],
    [101, 'рубль'],
    [111, 'рублей'],
    [6760, 'рублей'],
    [-2, 'рубля'],
  ])('%p → %p', (n, expected) => {
    expect(pluralRu(n, RUB)).toBe(expected);
  });
});
